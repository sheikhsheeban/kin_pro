"""Kin recall benchmark: a scripted week of overheard speech, questions with expected answers, and scoring.

week.txt         the clean transcript (160 lines over 7 days), with keep/drop and speaker ground truth
week_noisy.txt   the same lines with ASR-style noise (generated by `noise.py`; regenerate, don't hand-edit)
questions.yaml   99 questions with rule-checked expected answers and supporting line ids: the DEV set
                 (used to tune Prompts 3-5)
questions_test.yaml  153 more, written for Prompt 5 over the same week plus lines x.40-x.45: the held-out
                 TEST set, never used for tuning
gold_facts.yaml  what a perfect extractor would store (answer oracle, extraction precision/recall)

Run it with `uv run python scripts/eval_recall.py` (see that script for options).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
WEEK = HERE / "week.txt"
WEEK_NOISY = HERE / "week_noisy.txt"
QUESTIONS = HERE / "questions.yaml"
QUESTIONS_TEST = HERE / "questions_test.yaml"

ASK_AT = datetime(2026, 10, 5, 9, 0)  # every question is asked on Mon 5 Oct 2026, 09:00
VARIANTS = {"clean": WEEK, "noisy": WEEK_NOISY}


@dataclass(frozen=True)
class Line:
    id: str
    when: datetime
    speaker: str
    keep: bool
    text: str

    @property
    def day(self) -> int:
        return int(self.id.split(".")[0])


@dataclass(frozen=True)
class Question:
    id: str
    cat: str
    q: str
    expect: tuple[tuple[str, ...], ...] = ()
    min: int | None = None
    forbid: tuple[str, ...] = ()
    support: tuple[str, ...] = ()
    abstain: bool = False
    accept_abstain: bool = False
    smoke: bool = False
    answer: str = ""
    extra: dict = field(default_factory=dict)

    @property
    def needed(self) -> int:
        return len(self.expect) if self.min is None else self.min


def parse_week(text: str) -> list[Line]:
    lines: list[Line] = []
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        parts = [p.strip() for p in raw.split("|", 4)]
        if len(parts) != 5 or parts[3] not in ("keep", "drop"):
            raise ValueError(f"line {n}: expected 'id | YYYY-MM-DD HH:MM | speaker | keep/drop | text', got {raw!r}")
        lid, when, speaker, keep, body = parts
        lines.append(Line(lid, datetime.strptime(when, "%Y-%m-%d %H:%M"), speaker, keep == "keep", body))
    ids = [ln.id for ln in lines]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate line ids")
    return sorted(lines, key=lambda ln: (ln.when, ln.id))


def load_week(variant: str = "clean") -> list[Line]:
    return parse_week(VARIANTS[variant].read_text(encoding="utf-8"))


def _group(g) -> tuple[str, ...]:
    return tuple(str(x) for x in g) if isinstance(g, list) else (str(g),)


def load_questions(subset: str = "full") -> list[Question]:
    """full / dev: the original 99 (tuned on). test: the held-out 153. all: both. smoke: 20 of the dev set."""
    data = []
    if subset in ("full", "dev", "smoke", "all"):
        data += [dict(d, set="dev") for d in yaml.safe_load(QUESTIONS.read_text(encoding="utf-8"))["questions"]]
    if subset in ("test", "all"):
        data += [dict(d, set="test") for d in yaml.safe_load(QUESTIONS_TEST.read_text(encoding="utf-8"))["questions"]]
    out = []
    for d in data:
        d = dict(d)
        q = Question(
            id=d.pop("id"),
            cat=d.pop("cat"),
            q=d.pop("q"),
            expect=tuple(_group(g) for g in d.pop("expect", [])),
            min=d.pop("min", None),
            forbid=tuple(str(f) for f in d.pop("forbid", [])),
            support=tuple(str(s) for s in d.pop("support", [])),
            abstain=bool(d.pop("abstain", False)),
            accept_abstain=bool(d.pop("accept_abstain", False)),
            smoke=bool(d.pop("smoke", False)),
            answer=str(d.pop("answer", "")),
            extra=d,
        )
        out.append(q)
    if subset == "smoke":
        out = [q for q in out if q.smoke]
    return out
